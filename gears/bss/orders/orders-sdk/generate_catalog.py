#!/usr/bin/env python3
"""Generate Rust identifiers from the reviewed S1-02 inventory, never from implementation tests."""
import argparse, json, subprocess
from pathlib import Path
HERE = Path(__file__).resolve().parent
catalog = json.loads((HERE/'contracts/catalog.json').read_text())
def variant(s): return ''.join(x.title() for x in s.replace('-', '_').split('_'))
s = '// Generated by generate_catalog.py from the reviewed S1-02 catalog.\n'
s += 'use toolkit_canonical_errors::ProblemCategory;\nuse toolkit_gts::gts_id;\nuse serde::{Deserialize, Serialize};\n'
for name, values in [('OrderState', catalog['states']), ('Trigger', catalog['triggers']), ('EventKind', [e['name'] for e in catalog['events']]), ('Reason', [e['reason'] for e in catalog['errors']])]:
 if name == 'EventKind': s += '#[expect(clippy::enum_variant_names, reason = "Published event identifiers retain the Orders prefix")]\n'
 s += f'/// Closed `{name}` registry from the Orders design.\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]\npub enum {name} {{\n'
 for value in values:
  v = value if name == 'EventKind' else variant(value)
  s += f'    /// `{value}`.\n    #[serde(rename = "{value}")]\n    {v},\n'
 s += '}\n'
 ident = (lambda value: value) if name == 'EventKind' else variant
 s += f'impl {name} {{\n    /// All registered values.\n    pub const ALL: &\'static [Self] = &[\n'
 for value in values:s += f'        Self::{ident(value)},\n'
 s += '    ];\n'
 if name == 'OrderState':
  # The catalog's terminal set (one owner: the domain state table and claim release read it).
  assert set(catalog['terminal_states']) <= set(values)
  s += '    /// The terminal states: no catalog transition leaves them.\n    pub const TERMINAL: &\'static [Self] = &[\n'
  for value in catalog['terminal_states']:s += f'        Self::{ident(value)},\n'
  s += '    ];\n'
 s += f'    /// The registered token: the serde (wire and stored) name.\n    #[must_use]\n    pub const fn token(self) -> &\'static str {{\n        match self {{\n'
 for value in values:s += f'            Self::{ident(value)} => "{value}",\n'
 s += '        }\n    }\n'
 s += f'    /// The value a registered [`token`](Self::token) names; `None` for any other spelling.\n    #[must_use]\n    pub fn from_token(token: &str) -> Option<Self> {{\n        match token {{\n'
 for value in values:s += f'            "{value}" => Some(Self::{ident(value)}),\n'
 s += '            _ => None,\n        }\n    }\n}\n'
s += '''
/// Transport-neutral identity of a registered business refusal: its token, the stable
/// `error_code`, GTS registry key and canonical category. The HTTP binding (status code) is the
/// gear REST layer's (`orders/src/api/rest/wire.rs`, D-219).
#[derive(Debug, Clone, Copy)]
pub struct ReasonMapping {
    pub reason: &'static str,
    pub code: &'static str,
    pub gts_id: &'static str,
    pub category: ProblemCategory,
}
impl Reason {
    /// Authoritative reason identity and wire classification.
    #[must_use]
    pub const fn mapping(self) -> ReasonMapping {
        REASON_MAPPINGS[self as usize]
    }
}
const REASON_MAPPINGS: &[ReasonMapping] = &[
'''
for e in catalog['errors']:
 s += f'            ReasonMapping {{ reason: "{e["reason"]}", code: "{e["error_code"]}", gts_id: gts_id!("{e["gts_registry_key"][4:]}"), category: ProblemCategory::{e["canonical_category"]} }},\n'
s += '];\n'
s += '''
/// A registered catalog operation: its identity and PDP resource/action. Registration does not
/// enable a handler; the REST method and path are the gear REST layer's
/// (`orders/src/api/rest/wire.rs`, D-219).
#[derive(Debug, Clone, Copy)]
pub struct Operation {
    pub id: &'static str,
    pub resource: &'static str,
    pub action: &'static str,
}
/// Every S1-02 catalog operation (the registered public contract). S2 delivers eight of them over
/// REST and the local SDK: the five draft authoring writes (`create`, `patch_order`, `add_line`,
/// `patch_line`, `remove_line`) and the three draft reads (`get`, `list`, `list_lines`). The
/// others stay registered: REST does not mount them and the local SDK answers unavailable.
pub const OPERATIONS: &[Operation] = &[
'''
for o in catalog['operations']:
 s += '    Operation { '+', '.join(f'{k}: "{o[v]}"' for k,v in [('id','id'),('resource','pdp_resource'),('action','pdp_action')])+' },\n'
s += '];\n'
# The gear-side REST bindings of the same catalog (D-219, ADR-0005): the per-reason HTTP status
# and the per-operation method/path. They are transport facts, so they live in the gear's REST
# layer, keyed by the SDK `Reason` and operation id.
w = '// Generated by orders-sdk/generate_catalog.py from the reviewed S1-02 catalog.\n'
w += '//! The REST wire bindings of the SDK catalog (D-219): each registered reason\'s HTTP status and\n'
w += '//! each catalog operation\'s method and path. The SDK carries only transport-neutral identity.\n'
w += 'use bss_orders_sdk::catalog::Reason;\n'
w += '''
/// The registered HTTP status of a refusal reason. It may differ from the canonical category\'s
/// default within the same status class (`precondition-failed` 412, `expected-version-required`
/// 428).
#[must_use]
#[expect(
    clippy::match_same_arms,
    reason = "One generated arm per registered reason keeps the table reviewable against the catalog"
)]
pub const fn reason_status(reason: Reason) -> u16 {
    match reason {
'''
for e in catalog['errors']:
 w += f'        Reason::{variant(e["reason"])} => {e["http_status"]},\n'
w += '''    }
}

/// The REST binding of one catalog operation, keyed by its SDK operation id.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Route {
    pub id: &'static str,
    pub method: &'static str,
    pub path: &'static str,
}
/// The REST binding of every catalog operation, in catalog order. Listing a route does not mount
/// it; the delivered set is `DELIVERED_OPERATIONS`.
pub const ROUTES: &[Route] = &[
'''
for o in catalog['operations']:
 w += f'    Route {{ id: "{o["id"]}", method: "{o["method"]}", path: "{o["path"]}" }},\n'
w += '''];

/// The REST binding of a catalog operation id.
#[must_use]
pub fn route(id: &str) -> Option<&'static Route> {
    ROUTES.iter().find(|route| route.id == id)
}
'''
def fmt(text):
 # rustfmt through stdin keeps check mode read-only.
 return subprocess.run(['rustfmt', '--edition', '2024'], input=text, text=True, check=True, capture_output=True).stdout
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
outputs=[(HERE/'src/catalog.rs',fmt(s)),(HERE.parent/'orders/src/api/rest/wire.rs',fmt(w))]
for path,formatted in outputs:
 if args.check:
  if not path.exists() or path.read_text()!=formatted:raise SystemExit(f'Rust catalog drift in {path.name}; regenerate and review')
 else:path.write_text(formatted)
print('Rust contract catalog verified' if args.check else 'Rust contract catalog generated')
