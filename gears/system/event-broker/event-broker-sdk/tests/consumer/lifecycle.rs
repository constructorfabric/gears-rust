//! Consumer-handle lifecycle against the real broker: independent handles, each
//! exposing the subscription slots its parallelism created.

use std::sync::Arc;
use std::time::Duration;

use async_trait::async_trait;
use event_broker::test_support::StaticTypesRegistry;
use event_broker_sdk::{
    ConsumerBuilder, ConsumerError, ConsumerGroupKind, ConsumerGroupQuery, ConsumerGroupRef,
    ConsumerProfile, CreateConsumerGroupRequest, Delivery, EventBrokerError, EventHandler, EventV1,
    Fallback, GtsInstanceId, HandlerOutcome, InMemoryOffsetManager, gts_id,
};
use serde_json::json;
use tokio::sync::Notify;

use super::common::{fixture_from_catalog, publish_json, topic, topic_fixture_with_heartbeat};
use super::doubles::SeekFaultBroker;

const ORDERS_TOPIC: &str = gts_id!("cf.core.events.topic.v1~cf.core.orders.topic.v1");
const PAYMENTS_TOPIC: &str = gts_id!("cf.core.events.topic.v1~cf.core.payments.topic.v1");
const ORDER_PLACED: &str = gts_id!("cf.core.events.event.v1~cf.core.orders.placed.v1~");

/// Bounds every wait of the stop tests from the start to the `stop()`.
const BOUND: Duration = Duration::from_secs(5);

/// The broker's heartbeat in the stop test: far above `BOUND`, so a stream that
/// carried its last event stays silent past `BOUND`.
const IDLE_HEARTBEAT: Duration = Duration::from_secs(30);

struct NoopHandler;

#[async_trait]
impl EventHandler<serde_json::Value> for NoopHandler {
    async fn handle(
        &self,
        _event: EventV1,
        _delivery: &Delivery,
    ) -> Result<HandlerOutcome, ConsumerError> {
        Ok(HandlerOutcome::Success)
    }
}

/// Notifies `delivered` at each event it handles.
struct NotifyingHandler {
    delivered: Arc<Notify>,
}

#[async_trait]
impl EventHandler<serde_json::Value> for NotifyingHandler {
    async fn handle(
        &self,
        _event: EventV1,
        _delivery: &Delivery,
    ) -> Result<HandlerOutcome, ConsumerError> {
        self.delivered.notify_one();
        Ok(HandlerOutcome::Success)
    }
}

#[tokio::test]
async fn multiple_consumer_handles_run_with_independent_lifecycle() {
    let fixture = fixture_from_catalog(StaticTypesRegistry::of(json!([
        { "id": ORDERS_TOPIC, "partitions": 4 },
        { "id": PAYMENTS_TOPIC, "partitions": 4 },
    ])))
    .await;

    let orders = ConsumerBuilder::new(fixture.broker.clone())
        .subject_tenant(fixture.ctx.subject_tenant_id())
        .ownership_filter(event_broker_sdk::OwnershipFilter::EntireTenant)
        .security_context(fixture.ctx.clone())
        .group(ConsumerGroupRef::auto_anonymous("orders-handle"))
        .topics([topic(ORDERS_TOPIC)])
        .profile(ConsumerProfile::low_latency())
        .parallelism(2)
        .offset_manager(InMemoryOffsetManager::new(Fallback::Earliest))
        .handler(NoopHandler)
        .start()
        .await
        .expect("orders consumer starts");
    let payments = ConsumerBuilder::new(fixture.broker.clone())
        .subject_tenant(fixture.ctx.subject_tenant_id())
        .ownership_filter(event_broker_sdk::OwnershipFilter::EntireTenant)
        .security_context(fixture.ctx.clone())
        .group(ConsumerGroupRef::auto_anonymous("payments-handle"))
        .topics([topic(PAYMENTS_TOPIC)])
        .profile(ConsumerProfile::high_throughput())
        .parallelism(1)
        .offset_manager(InMemoryOffsetManager::new(Fallback::Latest))
        .handler(NoopHandler)
        .start()
        .await
        .expect("payments consumer starts");

    for _ in 0..200 {
        if orders.subscriptions().len() == 2 && payments.subscriptions().len() == 1 {
            break;
        }
        tokio::time::sleep(Duration::from_millis(10)).await;
    }

    let order_subscriptions = orders.subscriptions();
    let payment_subscriptions = payments.subscriptions();
    assert_eq!(order_subscriptions.len(), 2);
    assert_eq!(payment_subscriptions.len(), 1);
    assert!(
        order_subscriptions
            .iter()
            .all(|id| !payment_subscriptions.contains(id))
    );

    orders.stop().await.expect("orders handle stops");
    payments.stop().await.expect("payments handle stops");
}

/// The slots of an auto-anonymous consumer join the one group the consumer creates
/// when it starts, and that group splits the topic's four partitions between them,
/// two each, as two JOINs against one group do. The group's id and `created_at` are
/// generated by the broker, so they are read back rather than fixed.
#[tokio::test]
async fn the_slots_of_one_auto_anonymous_consumer_share_one_group() {
    let fixture = fixture_from_catalog(StaticTypesRegistry::of(
        json!([{ "id": ORDERS_TOPIC, "partitions": 4 }]),
    ))
    .await;

    let handle = ConsumerBuilder::new(fixture.broker.clone())
        .subject_tenant(fixture.ctx.subject_tenant_id())
        .ownership_filter(event_broker_sdk::OwnershipFilter::EntireTenant)
        .security_context(fixture.ctx.clone())
        .group(ConsumerGroupRef::auto_anonymous("shared-slots"))
        .topics([topic(ORDERS_TOPIC)])
        .parallelism(2)
        .offset_manager(InMemoryOffsetManager::new(Fallback::Earliest))
        .handler(NoopHandler)
        .start()
        .await
        .expect("the consumer starts");

    for _ in 0..200 {
        if handle.subscriptions().len() == 2 {
            break;
        }
        tokio::time::sleep(Duration::from_millis(10)).await;
    }
    let subscriptions = handle.subscriptions();
    let [first, second] = subscriptions.as_slice() else {
        panic!("expected one subscription per slot, saw {subscriptions:?}");
    };

    let groups = fixture
        .broker
        .list_consumer_groups(&fixture.ctx, ConsumerGroupQuery::default())
        .await
        .expect("consumer groups listed");
    let [group] = groups.items.as_slice() else {
        panic!("expected the consumer's one group, saw {:?}", groups.items);
    };
    assert_eq!(
        (
            group.tenant,
            group.owner_principal,
            group.kind,
            group.description.as_deref(),
        ),
        (
            fixture.ctx.subject_tenant_id(),
            fixture.ctx.subject_id(),
            ConsumerGroupKind::Anonymous,
            None,
        )
    );

    let mut assigned = Vec::new();
    for id in [first, second] {
        let subscription = fixture
            .broker
            .get_subscription(&fixture.ctx, *id)
            .await
            .expect("slot subscription read");
        assert_eq!(subscription.consumer_group, group.id);
        let mut partitions = subscription
            .assigned
            .iter()
            .map(|slot| (slot.topic.to_string(), slot.partition))
            .collect::<Vec<_>>();
        partitions.sort();
        assigned.push(partitions);
    }
    assigned.sort();
    assert_eq!(
        assigned,
        vec![
            vec![(ORDERS_TOPIC.to_owned(), 0), (ORDERS_TOPIC.to_owned(), 1)],
            vec![(ORDERS_TOPIC.to_owned(), 2), (ORDERS_TOPIC.to_owned(), 3)],
        ]
    );

    handle.stop().await.expect("the consumer stops");
}

/// A group named by its GTS reference has to be resolved to an id before a consumer
/// can join it, so `start()` refuses the consumer and no group is created.
#[tokio::test]
async fn a_consumer_naming_its_group_by_gts_reference_is_refused_at_start() {
    let fixture = fixture_from_catalog(StaticTypesRegistry::of(
        json!([{ "id": ORDERS_TOPIC, "partitions": 1 }]),
    ))
    .await;
    let named_group = GtsInstanceId::try_new(gts_id!(
        "cf.core.events.consumer_group.v1~cf.core.orders.workers.v1"
    ))
    .expect("valid consumer group GTS instance id");

    let started = ConsumerBuilder::new(fixture.broker.clone())
        .subject_tenant(fixture.ctx.subject_tenant_id())
        .ownership_filter(event_broker_sdk::OwnershipFilter::EntireTenant)
        .security_context(fixture.ctx.clone())
        .group(ConsumerGroupRef::gts(named_group))
        .topics([topic(ORDERS_TOPIC)])
        .offset_manager(InMemoryOffsetManager::new(Fallback::Earliest))
        .handler(NoopHandler)
        .start()
        .await;

    let Err(EventBrokerError::InvalidConsumerOptions { detail }) = started else {
        panic!(
            "expected the start to be refused, got {:?}",
            started.map(|_| ())
        );
    };
    assert_eq!(
        detail,
        "consumer group GTS reference \
         'gts.cf.core.events.consumer_group.v1~cf.core.orders.workers.v1' must be resolved \
         before startup"
    );
    let groups = fixture
        .broker
        .list_consumer_groups(&fixture.ctx, ConsumerGroupQuery::default())
        .await
        .expect("consumer groups listed");
    assert!(
        groups.items.is_empty(),
        "expected no consumer group, saw {:?}",
        groups.items
    );
}

/// The in-process broker checks a new group's `description` the way the REST
/// surface does: an over-long one is refused before the group exists.
#[tokio::test]
async fn in_process_group_creation_rejects_an_over_long_description() {
    let fixture = fixture_from_catalog(StaticTypesRegistry::of(
        json!([{ "id": ORDERS_TOPIC, "partitions": 1 }]),
    ))
    .await;

    let err = fixture
        .broker
        .create_consumer_group(
            &fixture.ctx,
            CreateConsumerGroupRequest {
                client_agent: "lifecycle-test".to_owned(),
                description: Some("d".repeat(1025)),
            },
        )
        .await
        .unwrap_err();

    // The answer crosses the canonical error, which carries the reason but
    // not the field name or the rule's wording.
    match err {
        EventBrokerError::InvalidTextField {
            field,
            detail,
            reason,
        } => assert_eq!(
            (field, detail.as_str(), reason),
            ("", "Request validation failed", "field_too_long")
        ),
        other => panic!("expected InvalidTextField, got {other:?}"),
    }
}

/// A slot waits for its stream's next frame between events, and `stop()` ends that
/// wait at once instead of when the frame comes. The delivered event shows the
/// stream open and read; after it the broker sends nothing until its heartbeat,
/// `IDLE_HEARTBEAT` (30 s) later. So the stop takes one wake of the slot's cancel,
/// far inside `BOUND` (5 s), and a stop that waits for that heartbeat lasts nearly
/// 30 s, six times `BOUND`.
#[tokio::test]
async fn stopping_a_consumer_does_not_wait_for_its_streams_next_frame() {
    let fixture = topic_fixture_with_heartbeat(ORDERS_TOPIC, ORDER_PLACED, 1, IDLE_HEARTBEAT).await;
    let delivered = Arc::new(Notify::new());
    let start = ConsumerBuilder::new(fixture.broker.clone())
        .subject_tenant(fixture.ctx.subject_tenant_id())
        .ownership_filter(event_broker_sdk::OwnershipFilter::EntireTenant)
        .security_context(fixture.ctx.clone())
        .group(ConsumerGroupRef::auto_anonymous("stopped-between-frames"))
        .topics([topic(ORDERS_TOPIC)])
        .offset_manager(InMemoryOffsetManager::new(Fallback::Earliest))
        .handler(NotifyingHandler {
            delivered: delivered.clone(),
        })
        .start();
    let handle = tokio::time::timeout(BOUND, start)
        .await
        .expect("the consumer starts within the bound")
        .expect("the consumer starts");
    tokio::time::timeout(
        BOUND,
        publish_json(
            &fixture.broker,
            &fixture.ctx,
            ORDER_PLACED,
            "order-1",
            None,
            json!({}),
        ),
    )
    .await
    .expect("the event is published within the bound");
    tokio::time::timeout(BOUND, delivered.notified())
        .await
        .expect("the event is delivered within the bound");

    let stopped = tokio::time::timeout(BOUND, handle.stop()).await;

    let Ok(Ok(())) = stopped else {
        panic!("expected the consumer to stop within the bound, got {stopped:?}");
    };
}

/// A slot whose stream never sends its first frame, as a connection that goes silent
/// before it, still stops at once: the wait for the first frame watches the slot's
/// cancel too. The double notifies as it hands out the silent stream, which the slot
/// then awaits. So the stop takes one wake of the slot's cancel, far inside `BOUND`
/// (5 s), and a stop that waits for that frame never ends.
#[tokio::test]
async fn stopping_a_consumer_does_not_wait_for_its_streams_first_frame() {
    let fixture = fixture_from_catalog(StaticTypesRegistry::of(
        json!([{ "id": ORDERS_TOPIC, "partitions": 1 }]),
    ))
    .await;
    let faulty = SeekFaultBroker::new(fixture.broker.clone(), 0, false).with_silent_open();
    let silent_open = faulty.silent_open.clone();
    let start = ConsumerBuilder::new(Arc::new(faulty))
        .subject_tenant(fixture.ctx.subject_tenant_id())
        .ownership_filter(event_broker_sdk::OwnershipFilter::EntireTenant)
        .security_context(fixture.ctx.clone())
        .group(ConsumerGroupRef::auto_anonymous(
            "stopped-before-first-frame",
        ))
        .topics([topic(ORDERS_TOPIC)])
        .offset_manager(InMemoryOffsetManager::new(Fallback::Earliest))
        .handler(NoopHandler)
        .start();
    let handle = tokio::time::timeout(BOUND, start)
        .await
        .expect("the consumer starts within the bound")
        .expect("the consumer starts");
    tokio::time::timeout(BOUND, silent_open.notified())
        .await
        .expect("the consumer opens its stream within the bound");

    let stopped = tokio::time::timeout(BOUND, handle.stop()).await;

    let Ok(Ok(())) = stopped else {
        panic!("expected the consumer to stop within the bound, got {stopped:?}");
    };
}
