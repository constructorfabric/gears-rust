-- Dialect:  PostgreSQL. The gear's migrations also target SQLite and
-- MySQL/MariaDB; this file is the statements they emit on PostgreSQL.
--
-- The ingest outbox tables are not here: toolkit-db creates and owns them,
-- under the prefix `event_broker__ob_default` (`_trace`, `_body`,
-- `_partitions`, `_incoming`, `_outgoing`, `_dead_letters`, `_processor`,
-- `_vacuum_counter`). Events are not here either: each storage backend keeps
-- its own event store.


-- ── Specification cache ──────────────────────────────────────────────────────
-- Topics and event types in one table, told apart by `kind` ('topic' |
-- 'event_type'). `id` is the stable integer surrogate other tables key a topic
-- by; it is never renumbered, since loading upserts by `gts_id`.
CREATE TABLE IF NOT EXISTS "event_broker_spec_cache" (
    "id"      bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    "gts_id"  varchar(1024) NOT NULL,
    "kind"    varchar(10)   NOT NULL,
    "payload" text          NOT NULL    -- the topic or event type as JSON, never queried into
);

CREATE UNIQUE INDEX "event_broker_spec_cache_gts_id_idx" ON "event_broker_spec_cache" ("gts_id");


-- ── Consumer groups ──────────────────────────────────────────────────────────
-- Persistent registry row; outlives every subscription and every cache wipe.
-- `kind` is 'anonymous' (minted by `POST /v1/consumer-groups`) or 'named'
-- (registered in `types_registry`). `tenant_id` and `owner_principal_id` come
-- from the creator's SecurityContext and never change.
CREATE TABLE IF NOT EXISTS "event_broker_consumer_group" (
    "id"                 varchar(1024) NOT NULL PRIMARY KEY,
    "kind"               varchar(9)    NOT NULL,
    "tenant_id"          uuid          NOT NULL,
    "owner_principal_id" uuid          NOT NULL,
    "description"        varchar(1024) NULL,
    "created_at"         timestamp with time zone NOT NULL
);

CREATE INDEX "event_broker_consumer_group_tenant_idx" ON "event_broker_consumer_group" ("tenant_id");


-- ── Cursors ──────────────────────────────────────────────────────────────────
-- The only persistent piece of a group's progress. `topic_id` is the spec
-- cache's surrogate id; `tenant_id` is copied from the owning group.
CREATE TABLE IF NOT EXISTS "event_broker_cursor" (
    "consumer_group" varchar(1024) NOT NULL,
    "topic_id"       bigint        NOT NULL,
    "partition"      integer       NOT NULL,
    "tenant_id"      uuid          NOT NULL,
    "offset"         bigint        NOT NULL,
    "updated_at"     timestamp with time zone NOT NULL,
    PRIMARY KEY ("consumer_group", "topic_id", "partition")
);

CREATE INDEX "event_broker_cursor_tenant_idx" ON "event_broker_cursor" ("tenant_id");


-- ── Producers ────────────────────────────────────────────────────────────────
-- Broker-minted at `POST /v1/producers` and bound to the registering
-- principal (`owner_id`). `mode` is 'chained' or 'monotonic' and never
-- changes; stateless producers do not register. `client_agent` is a
-- diagnostic hint only, never used for dedup, authz or ownership.
CREATE TABLE IF NOT EXISTS "event_broker_producer" (
    "id"           uuid         NOT NULL PRIMARY KEY,
    "tenant_id"    uuid         NOT NULL,
    "owner_id"     uuid         NOT NULL,
    "mode"         varchar(9)   NOT NULL,
    "client_agent" varchar(256) NOT NULL,
    "created_at"   timestamp with time zone NOT NULL
);

CREATE INDEX "event_broker_producer_tenant_idx" ON "event_broker_producer" ("tenant_id");


-- ── Producer chain state ─────────────────────────────────────────────────────
-- One row per (producer_id, topic): the highest `meta.sequence` accepted from
-- that producer on that topic. The backend partition is not part of the chain.
-- Writers to one row serialize on it, so one writer advances `last_sequence`
-- at a time. `tenant_id` is copied from the owning producer.
CREATE TABLE IF NOT EXISTS "event_broker_producer_sequence" (
    "producer_id"   uuid          NOT NULL,
    "topic"         varchar(1024) NOT NULL,
    "tenant_id"     uuid          NOT NULL,
    "last_sequence" bigint        NOT NULL,
    "updated_at"    timestamp with time zone NOT NULL,
    PRIMARY KEY ("producer_id", "topic")
);

CREATE INDEX "event_broker_producer_sequence_tenant_idx" ON "event_broker_producer_sequence" ("tenant_id");


-- ── Outbox identity ──────────────────────────────────────────────────────────
-- The 64-bit identity of each ingest outbox group, keyed by the group's
-- toolkit-db queue name: the high half of every fence key the group appends
-- under.
CREATE TABLE IF NOT EXISTS "event_broker__outbox_identity" (
    "name"       varchar(63) NOT NULL PRIMARY KEY,
    "outbox_id"  varchar(16) NOT NULL,    -- 16 lowercase hex digits
    "created_at" timestamp with time zone NOT NULL
);


-- ── Topic binding ────────────────────────────────────────────────────────────
-- One topic's provisioning record: which backend log it has, and whether it
-- is provisioned. `attempt_at` is database time as 24-character text and is
-- compared as text. `partitions` and the retention columns are set once
-- provisioned; NULL retention means unbounded. `retention_version` is bumped
-- by every write of the retention columns or of `retention_confirmed`, and the
-- mark before a re-provision call and the retention write after it
-- compare-and-set on it; `retention_confirmed` is false while the backend may
-- hold a retention other than the recorded one.
CREATE TABLE IF NOT EXISTS "event_broker__topic_binding" (
    "topic_uuid"           uuid          NOT NULL PRIMARY KEY,    -- GtsId::to_uuid(topic_id)
    "topic_id"             varchar(1024) NOT NULL,                -- for operators, not indexed
    "log_id"               uuid          NOT NULL,
    "state"                varchar(12)   NOT NULL,                -- 'provisioning' | 'provisioned'
    "attempt_at"           varchar(24)   NOT NULL,
    "partitions"           bigint        NULL,
    "retention_max_age_ms" bigint        NULL,
    "retention_max_bytes"  bigint        NULL,
    "retention_version"    bigint        NOT NULL,
    "retention_confirmed"  bool          NOT NULL
);
